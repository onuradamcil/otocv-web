create unique index if not exists vehicles_storage_key_idx on public.vehicles using btree (storage_key);
create index if not exists vehicles_kasko_bitis_idx on public.vehicles using btree (kasko_end_date);
create index if not exists vehicles_muayene_bitis_idx on public.vehicles using btree (inspection_end_date);
