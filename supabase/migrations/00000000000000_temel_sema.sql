-- Bu projede migration'lar bir noktada başladı ama TEMEL TABLOLAR ondan önce
-- Supabase panelinden elle açılmıştı. Sonuç ölçüldü:
--
--   vehicles  -> hiçbir migration OLUŞTURMUYOR, 25 migration REFERANS veriyor
--   listings  -> hiçbir migration OLUŞTURMUYOR, 10 migration REFERANS veriyor
--   profiles  -> hiçbir migration OLUŞTURMUYOR,  6 migration REFERANS veriyor
--
-- Yani depodaki migration'lar boş bir veritabanına uygulanamıyordu: ilk
-- `vehicles` referansında duruyordu. Bu, test/staging ortamı kurmayı, yeni
-- bir geliştiricinin ortamını ayağa kaldırmasını ve olası bir kurtarma
-- senaryosunu imkânsız kılıyordu.
--
-- ⚠ Veritabanının PITR yedeği de yok. Bu dosya, şemayı git'e alarak o
-- riskin ŞEMA tarafını kapatıyor. VERİYİ kapatmıyor — veri yedeği ayrı bir
-- iş.
--
-- -------------------------------------------------------------------------
-- NASIL ÜRETİLDİ
-- -------------------------------------------------------------------------
-- Canlı veritabanının katalogları (`pg_class`, `pg_attribute`,
-- `pg_constraint`, `pg_indexes`, `pg_policies`) OKUNARAK üretildi. Elle
-- yazılmadı, tahmin edilmedi.
--
-- ⚠ BU DOSYA CANLI VERİTABANINA UYGULANMADI ve uygulanmamalı. Orada zaten
-- her şey var; işi yalnızca BOŞ bir veritabanında zinciri başlatmak.
-- Yine de tamamen idempotent yazıldı (`if not exists`, `drop policy if
-- exists`, yinelenen kısıtta sessiz geçiş): yanlışlıkla çalıştırılsa bile
-- hiçbir tabloyu, kolonu ya da satırı değiştirmez.
--
-- -------------------------------------------------------------------------
-- KAPSAM — BİLEREK DAR
-- -------------------------------------------------------------------------
-- Yalnızca "hiçbir migration'ın oluşturmadığı" şeyler burada:
--   · 10 tablo + kısıtları + indeksleri + RLS
--   · 12 politika (panelden açılmış olanlar)
--
-- BURADA OLMAYANLAR ve sebebi:
--   · 16 tablo  -> zaten kendi migration'ları var
--   · 8 tetikleyici ve 8 tetikleyici fonksiyonu -> hepsi migration'larda;
--     buraya da konsaydı sıfırdan kurulumda "zaten var" hatası verirdi
--   · 9 politika -> migration'larda tanımlı
--   · RPC'ler    -> migration'larda
--   · vehicles_yedek_20260819 -> geçici yedek tablosu, şemanın parçası değil
-- =========================================================================

-- =========================================================================
-- 1. KATALOG TABLOLARI
-- Araç markası/serisi/modeli/donanımı. Sihirbazın kaskadı ve anasayfa
-- süzgeç ağacı bunlardan besleniyor (49 / 822 / 3.591 / 23.138 satır).
-- =========================================================================
create table if not exists public.car_brands (
  id bigint generated by default as identity,
  name character varying(100) not null,
  created_at timestamp with time zone default now()
);

create table if not exists public.car_series (
  id bigint generated by default as identity,
  brand_id bigint,
  name character varying(100) not null,
  created_at timestamp with time zone default now()
);

create table if not exists public.car_models (
  id bigint generated by default as identity,
  series_id bigint,
  name character varying(100) not null,
  created_at timestamp with time zone default now()
);

create table if not exists public.car_packages (
  id bigint generated by default as identity,
  model_id bigint,
  name character varying(100) not null,
  created_at timestamp with time zone default now()
);

-- =========================================================================
-- 2. KULLANICI PROFİLİ
-- `auth.users`a bire bir bağlı. Silinme CASCADE: hesap silinince profil de.
-- =========================================================================
create table if not exists public.profiles (
  id uuid not null,
  first_name text not null,
  last_name text not null,
  phone_number text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  is_premium boolean default false,
  pazarlama_izni boolean default false not null,
  pazarlama_izni_at timestamp with time zone,
  avatar_yolu text
);

-- =========================================================================
-- 3. ARAÇ — ÜRÜNÜN MERKEZİ TABLOSU
-- Birincil anahtar PLAKA. `pin_code` karne paylaşım anahtarı,
-- `gorunurluk` aramada çıkıp çıkmayacağını belirliyor.
-- =========================================================================
create table if not exists public.vehicles (
  plate_number character varying(20) not null,
  km integer not null,
  brand character varying(100) not null,
  model character varying(100) not null,
  year integer not null,
  package character varying(100) not null,
  kasko_end_date date,
  inspection_end_date date not null,
  trust_score integer default 0 not null,
  created_at timestamp with time zone default now(),
  image_url text,
  traffic_insurance_end_date date,
  fuel_type text,
  transmission text,
  color text,
  tramer_status text default 'Bilmiyorum'::text not null,
  tramer_amount numeric,
  pin_code text,
  user_id uuid,
  series character varying(100),
  title text,
  city text,
  district text,
  body_type text,
  description text,
  damage_report jsonb default '{}'::jsonb,
  selected_features jsonb default '[]'::jsonb,
  engine_capacity text,
  trust_breakdown jsonb,
  storage_key uuid default gen_random_uuid() not null,
  sahipsiz_kaldi_at timestamp with time zone,
  belge_erisimi_kisitli boolean default false not null,
  has_warranty boolean,
  is_first_owner boolean,
  vehicle_condition text,
  gorunurluk text default 'listelenebilir'::text not null
);

-- =========================================================================
-- 4. VİTRİN KAYDI
-- Aracın pazaryeri vitrininde görünmesi. `status='active'` olan kayıt
-- "vitrin katmanı" demek ve karne PIN'ini dışarı açıyor.
-- =========================================================================
create table if not exists public.listings (
  id bigint generated by default as identity,
  vehicle_plate character varying(50),
  user_id uuid,
  title character varying(255) not null,
  description text not null,
  price numeric(12,2),
  city character varying(100) not null,
  district character varying(100) not null,
  tramer_amount numeric(12,2) default 0,
  status character varying(20) default 'active'::character varying,
  views_count integer default 0,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now(),
  is_featured boolean default false,
  is_urgent boolean default false,
  is_trade_in boolean default false,
  previous_price numeric(12,2),
  neighborhood character varying(100),
  favorite_count integer default 0,
  contact_phone character varying(20)
);

-- =========================================================================
-- 5. BAKIM KAYITLARI · BİLDİRİMLER · SİHİRBAZ TASLAĞI
-- =========================================================================
-- ⚠ `bigserial`: canlıda kolon `nextval('maintenance_records_id_seq')`
-- varsayılanıyla duruyor (identity DEĞİL). `bigserial` birebir aynı yapıyı
-- kuruyor: bigint kolon + sahipli sequence + default.
create table if not exists public.maintenance_records (
  id bigserial,
  vehicle_plate character varying(20),
  shop_name character varying(100) not null,
  km_at_service integer not null,
  cost numeric(10,2) not null,
  summary text not null,
  created_at timestamp with time zone default now(),
  service_date date,
  service_type text,
  next_service_km integer,
  invoice_path text,
  yukleyen_user_id uuid
);

create table if not exists public.notifications (
  id uuid default gen_random_uuid() not null,
  user_id uuid not null,
  vehicle_id uuid,
  title character varying(255) not null,
  message text not null,
  type character varying(50) default 'info'::character varying not null,
  is_read boolean default false not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  hedef_yol text
);

create table if not exists public.vehicle_drafts (
  id uuid default gen_random_uuid() not null,
  user_id uuid,
  current_step integer default 1,
  form_data jsonb default '{}'::jsonb,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

