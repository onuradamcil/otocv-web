create index if not exists vehicles_sahipsiz_idx on public.vehicles using btree (sahipsiz_kaldi_at) where (sahipsiz_kaldi_at is not null);
create index if not exists vehicles_gorunurluk_idx on public.vehicles using btree (gorunurluk) where (gorunurluk = 'listelenebilir'::text);

create index if not exists bakim_servis_tarihi_idx on public.maintenance_records using btree (service_date);
create index if not exists bakim_fatura_yolu_idx on public.maintenance_records using btree (vehicle_plate) where (invoice_path is not null);

create index if not exists notifications_user_id_idx on public.notifications using btree (user_id);
create index if not exists notifications_is_read_idx on public.notifications using btree (is_read);

