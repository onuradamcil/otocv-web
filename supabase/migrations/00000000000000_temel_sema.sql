create index if not exists idx_listings_status on public.listings using btree (status);
create index if not exists idx_listings_is_featured on public.listings using btree (is_featured);
create index if not exists idx_listings_location on public.listings using btree (city, district);
create index if not exists idx_listings_price on public.listings using btree (price);

-- PIN aramaları büyük/küçük harf duyarsız; tekillik de öyle olmalı.
