-- ⚠ ARAÇ VE VİTRİN KAYDI DIŞARIYA KAPALI. Anasayfa aramasının bunları
-- görebilmesi RLS'in gevşetilmesiyle DEĞİL, `arac_arama()` gibi
-- `security definer` fonksiyonların güvenli izdüşüm döndürmesiyle
-- sağlanıyor. Doğrudan tablo erişimi yalnızca sahibine.
drop policy if exists "Kullanıcılar kendi ilanlarını yönetebilir" on public.listings;
create policy "Kullanıcılar kendi ilanlarını yönetebilir" on public.listings
  for all using (auth.uid() = user_id);

drop policy if exists "Kullanıcılar sadece kendi garajına araç ekleyebilir" on public.vehicles;
create policy "Kullanıcılar sadece kendi garajına araç ekleyebilir" on public.vehicles
  for insert with check (auth.uid() = user_id);

drop policy if exists "Kullanıcılar kendi profillerini görebilir." on public.profiles;
create policy "Kullanıcılar kendi profillerini görebilir." on public.profiles
  for select using (auth.uid() = id);

drop policy if exists "Kullanıcı kendi taslağını görebilir ve yönetebilir" on public.vehicle_drafts;
create policy "Kullanıcı kendi taslağını görebilir ve yönetebilir" on public.vehicle_drafts
  for all using (auth.uid() = user_id);

drop policy if exists "Kullanıcılar sadece kendi bildirimlerini görüntüleyebilir." on public.notifications;
create policy "Kullanıcılar sadece kendi bildirimlerini görüntüleyebilir." on public.notifications
  for select using (auth.uid() = user_id);
drop policy if exists "Kullanıcılar kendi bildirimlerini oluşturabilir" on public.notifications;
create policy "Kullanıcılar kendi bildirimlerini oluşturabilir" on public.notifications
  for insert with check (auth.uid() = user_id);
drop policy if exists "Kullanıcılar sadece kendi bildirimlerini güncelleyebilir." on public.notifications;
create policy "Kullanıcılar sadece kendi bildirimlerini güncelleyebilir." on public.notifications
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Kullanıcılar sadece kendi bildirimlerini silebilir." on public.notifications;
create policy "Kullanıcılar sadece kendi bildirimlerini silebilir." on public.notifications
  for delete using (auth.uid() = user_id);

